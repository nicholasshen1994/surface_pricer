    def _date_convert(self, strDate):
        if type(strDate) == datetime.datetime:
            return strDate.date()
        elif type(strDate) == str:
            if '/' in strDate:
                return datetime.datetime.strptime(strDate, '%Y/%m/%d').date()
            elif '-' in strDate:
                return datetime.datetime.strptime(strDate, '%Y-%m-%d').date()
            elif len(strDate) == 8:
                return datetime.datetime.strptime(strDate, '%Y%m%d').date()
        elif type(strDate) == datetime.date:
            return strDate

    def IsHoliday(self, strDate):
        # 是节假日返回True
        dateDate = self._date_convert(strDate)
        # weekend is not Bizday
        weekday = dateDate.weekday()
        if weekday in self.weekend:
            return True
        if dateDate.strftime('%Y-%m-%d') in self.holiday:
            return True
        return False

    def IsLeapYear(self, year):
        if year % 100 == 0:
            if year % 400 == 0:
                return True
            else:
                return False
        elif year % 4 == 0:
            return True
        else:
            return False

    def IsBizDay(self, strDate):
        return not self.IsHoliday(strDate)

    def PreviousBizDay(self, strDate):
        dateDate = self._date_convert(strDate)
        td = datetime.timedelta(days=1)
        dateDate -= td
        while self.IsHoliday(dateDate):
            dateDate -= td
        return dateDate

    def FollowingBizDay(self, strDate):
        dateDate = self._date_convert(strDate)
        td = datetime.timedelta(days=1)
        dateDate += td
        while self.IsHoliday(dateDate):
            dateDate += td
        #end while
        return dateDate

    def FirstBizDayOfYear(self, year):
        year = int(year)
        return self.FollowingBizDay(self.PreviousBizDay("%d/01/01"%year))

    def LastBizDayOfYear(self, year):
        year = int(year)
        return self.PreviousBizDay("%d/01/01"%(year + 1))

    def FirstBizDayOfMonth(self, year, month):
        return self.FollowingBizDay(self.PreviousBizDay(datetime.date(year, month, 1)))

    def LastBizDayOfMonth(self, year, month):
        return self.PreviousBizDay(datetime.date(year + month // 12, (month) % 12 + 1, 1))

    def AddBizDay(self, strDate, day = 1):
        if day > 0:
            for i in range(round(day)):
                strDate = self.FollowingBizDay(strDate)
        elif day < 0:
            for i in range(round(-day)):
                strDate = self.PreviousBizDay(strDate)
        return strDate

    def GetAllBizDayBetween(self, startDate, endDate):
        result = []
        startDate = self._date_convert(startDate)
        endDate = self._date_convert(endDate)
        td = datetime.timedelta(days=1)
        curDate = self.FollowingBizDay((startDate-td))
        while curDate <= endDate:
            result.append(curDate)
            curDate = self.FollowingBizDay(curDate)
        return result

    def GetAllWeekDayBetween(self, startDate, endDate):
        result = []
        startDate = self._date_convert(startDate)
        endDate = self._date_convert(endDate)
        td = datetime.timedelta(days=1)
        curDate = startDate
        while curDate <= endDate:
            if curDate.weekday() <= 4:
                result.append(curDate)
            curDate += td
        return result

    def GetAllDayBetween(self, startDate, endDate):
        result = []
        startDate = self._date_convert(startDate)
        endDate = self._date_convert(endDate)
        td = datetime.timedelta(days=1)
        curDate = startDate
        while curDate <= endDate:
            result.append(curDate)
            curDate += td
        return result


